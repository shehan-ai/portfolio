// Navigation Functions
function goToHome() {
    document.getElementById('assignments').classList.remove('hidden');
    document.getElementById('assignmentDetail').classList.add('hidden');
    window.scrollTo(0, 0);
}

function scrollToAssignments() {
    document.getElementById('assignmentDetail').classList.add('hidden');
    document.getElementById('assignments').classList.remove('hidden');
    document.getElementById('assignments').scrollIntoView({ behavior: 'smooth' });
}

function viewAssignment(id) {
    const assignment = assignments.find(a => a.id === id);
    if (assignment) {
        document.getElementById('assignmentDetailContent').innerHTML = assignment.fullDetails;
        document.getElementById('assignments').classList.add('hidden');
        document.getElementById('assignmentDetail').classList.remove('hidden');

        // Show PDF if available
        if (assignmentPDFs[id]) {
            const pdfFile = assignmentPDFs[id];
            document.getElementById('pdfFrame').src = pdfFile;
            document.getElementById('pdfDownloadLink').href = pdfFile;
            document.getElementById('pdfViewer').classList.remove('hidden');
        } else {
            document.getElementById('pdfViewer').classList.add('hidden');
        }

        document.getElementById('assignmentDetail').scrollIntoView({ behavior: 'smooth' });
    }
}

// Populate Assignments Grid on Page Load
function initializeAssignments() {
    const grid = document.getElementById('assignmentsGrid');
    grid.innerHTML = assignments.map(assignment => {
        const highlights = assignment.guidelineHighlights ?
            `<div class="guidelines-preview">
                <strong>Key Info:</strong>
                <ul>
                    ${assignment.guidelineHighlights.map(h => `<li>${h}</li>`).join('')}
                </ul>
            </div>` : '';

        return `
            <div class="assignment-card" onclick="viewAssignment(${assignment.id})">
                <h3>${assignment.title}</h3>
                <p class="module">${assignment.module}</p>
                <p class="description">${assignment.shortDescription}</p>
                <span class="score ${assignment.scoreClass}">${assignment.score}</span>
                ${highlights}
                <button class="view-button">View Details</button>
            </div>
        `;
    }).join('');
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', initializeAssignments);
